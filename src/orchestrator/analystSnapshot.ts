/**
 * Analyst stage — cache a read-only tree export of the trusted mirror tip so
 * the grok analyst session can run confined to `cwd = <snapshot>` under the
 * `hercules-analyst` sandbox profile. Injectable I/O; never throws from ensure.
 *
 * Credentials live in a private GROK_HOME next to the snapshot root (never
 * inside the repo tree): only auth.json + agent_id are copied from the operator
 * grok home. That replaces the pre-1.0.13 deny-mount list, which grok CLI
 * ≥ 1.0.13 refuses to start with.
 */
import { randomBytes } from 'node:crypto';
import { existsSync } from 'node:fs';
import {
  chmod,
  copyFile,
  mkdir,
  readdir,
  rename,
  rm,
  stat,
  utimes,
  writeFile,
} from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';
import type { RepoConfig } from '../domain/repos.js';

/** Custom grok sandbox profile name, defined by `<snapshot>/.grok/sandbox.toml`. */
export const ANALYST_SANDBOX_PROFILE = 'hercules-analyst';

/** Credential filenames copied into the private analyst GROK_HOME — nothing else. */
export const ANALYST_GROK_HOME_CREDENTIALS = ['auth.json', 'agent_id'] as const;

export interface AnalystSnapshot {
  /** Directory the grok session runs in (always exists, always carries the sandbox profile). */
  readonly dir: string;
  /** Trusted default-branch sha the tree was exported at; null for the empty fallback. */
  readonly sha: string | null;
  /**
   * Private GROK_HOME (credentials only) for this snapshot root. Null when
   * operator auth.json is missing — caller must treat the analyst as unavailable.
   */
  readonly grokHome: string | null;
}

export interface AnalystSnapshotsOptions {
  /** Snapshot root, e.g. `<isolation root>/.analyst`. Layout: `<root>/<repoKey>/<sha>/`. */
  readonly root: string;
  readonly defaultBranchHead: (repo: RepoConfig) => Promise<string | null>;
  readonly exportTree: (repo: RepoConfig, sha: string, destDir: string) => Promise<void>;
  /**
   * Operator grok home to copy credentials from. Default: `$GROK_HOME` if set,
   * else `~/.grok`. Never written to.
   */
  readonly operatorGrokHome?: string;
  /** Snapshots retained per repo (newest by mtime). Default 2. */
  readonly keep?: number;
  readonly log?: (line: string) => void;
}

export interface AnalystSnapshots {
  /** Absolute path of the private GROK_HOME directory (may not exist yet). */
  readonly grokHomePath: string;
  /**
   * Ensure the private GROK_HOME exists with fresh credential copies.
   * Returns null and logs when operator auth.json is missing (no throw).
   */
  ensurePrivateHome(): Promise<string | null>;
  /** Snapshot for the repo's current trusted tip (cached per sha). Never throws: falls back to an empty sandboxed dir. */
  ensure(repo: RepoConfig): Promise<AnalystSnapshot>;
}

const REPO_KEY_RE = /^[A-Za-z0-9._-]+$/;
const SHA_RE = /^[0-9a-f]{7,40}$/i;
const MARKER = '.hercules-snapshot';
const EMPTY_NAME = '_empty';
const PRIVATE_HOME_NAME = '.grok-home';

/**
 * Pure: the `.grok/sandbox.toml` text. `extends = "strict"` (reads limited to
 * cwd + system paths, no child network). `deny` is always empty since grok CLI
 * ≥ 1.0.13 refuses to start when read-deny mounts for `~/.grok/{continuity,…}`
 * fail its bwrap self-check; confinement of those dirs is achieved instead by
 * spawning with a private `GROK_HOME` that holds only auth credentials (no
 * rules / continuity / projects).
 */
export function renderAnalystSandboxToml(): string {
  return [
    '# Generated by Hercules — confines the analyst grok session to this snapshot.',
    `[profiles.${ANALYST_SANDBOX_PROFILE}]`,
    'extends = "strict"',
    'restrict_network = true',
    'deny = []',
    '',
  ].join('\n');
}

/** Resolve the operator grok home (source of credentials; never mutated). */
export function resolveOperatorGrokHome(
  explicit?: string,
  env: NodeJS.ProcessEnv = process.env,
  home: string = homedir(),
): string {
  const fromOpt = explicit?.trim();
  if (fromOpt && fromOpt.length > 0) return fromOpt;
  const fromEnv = env['GROK_HOME']?.trim();
  if (fromEnv && fromEnv.length > 0) return fromEnv;
  return join(home, '.grok');
}

async function writeSandboxProfile(dir: string): Promise<void> {
  const grokDir = join(dir, '.grok');
  await mkdir(grokDir, { recursive: true });
  await writeFile(join(grokDir, 'sandbox.toml'), renderAnalystSandboxToml(), 'utf8');
}

async function writeMarker(dir: string, content: string): Promise<void> {
  await writeFile(join(dir, MARKER), content, 'utf8');
}

async function isReady(dir: string): Promise<boolean> {
  try {
    await stat(join(dir, MARKER));
    return true;
  } catch {
    return false;
  }
}

async function touchDir(dir: string): Promise<void> {
  const now = new Date();
  try {
    await utimes(dir, now, now);
  } catch {
    // best-effort
  }
}

function isRenameRace(err: unknown): boolean {
  if (err === null || typeof err !== 'object') return false;
  const code = (err as { code?: unknown }).code;
  return code === 'EEXIST' || code === 'ENOTEMPTY';
}

/**
 * Copy auth.json (+ agent_id when present) into `destHome` (mode 700 / 600).
 * Refreshes a file only when the source mtime is newer. Returns false when
 * auth.json is missing or unreadable — never throws.
 */
export async function refreshAnalystPrivateHome(input: {
  readonly destHome: string;
  readonly operatorGrokHome: string;
  readonly log?: (line: string) => void;
}): Promise<boolean> {
  const log = input.log ?? ((): void => {});
  const authSrc = join(input.operatorGrokHome, 'auth.json');
  if (!existsSync(authSrc)) {
    log(
      `[hercules] analyst: UNAVAILABLE — missing auth.json in ${input.operatorGrokHome}`,
    );
    return false;
  }

  try {
    await mkdir(input.destHome, { recursive: true, mode: 0o700 });
    await chmod(input.destHome, 0o700);
  } catch (err) {
    log(
      `[hercules] analyst: UNAVAILABLE — cannot create private GROK_HOME: ${String(err)}`,
    );
    return false;
  }

  for (const name of ANALYST_GROK_HOME_CREDENTIALS) {
    const src = join(input.operatorGrokHome, name);
    const dest = join(input.destHome, name);
    if (!existsSync(src)) {
      if (name === 'auth.json') {
        log(
          `[hercules] analyst: UNAVAILABLE — missing auth.json in ${input.operatorGrokHome}`,
        );
        return false;
      }
      continue;
    }
    try {
      const srcSt = await stat(src);
      let needsCopy = true;
      try {
        const destSt = await stat(dest);
        if (destSt.mtimeMs >= srcSt.mtimeMs) needsCopy = false;
      } catch {
        needsCopy = true;
      }
      if (needsCopy) {
        await copyFile(src, dest);
        await chmod(dest, 0o600);
      }
    } catch (err) {
      if (name === 'auth.json') {
        log(
          `[hercules] analyst: UNAVAILABLE — failed to copy auth.json: ${String(err)}`,
        );
        return false;
      }
      log(`[hercules] analyst: skip copy ${name}: ${String(err)}`);
    }
  }
  return true;
}

export function createAnalystSnapshots(opts: AnalystSnapshotsOptions): AnalystSnapshots {
  const operatorGrokHome = resolveOperatorGrokHome(opts.operatorGrokHome);
  const keep = opts.keep ?? 2;
  const log = opts.log ?? ((): void => {});
  const inFlight = new Map<string, Promise<AnalystSnapshot>>();
  const grokHomePath = join(opts.root, PRIVATE_HOME_NAME);

  async function ensurePrivateHome(): Promise<string | null> {
    const ok = await refreshAnalystPrivateHome({
      destHome: grokHomePath,
      operatorGrokHome,
      log,
    });
    return ok ? grokHomePath : null;
  }

  async function ensureEmpty(
    repoDir: string,
    reason: string,
    repoKey: string,
    grokHome: string | null,
  ): Promise<AnalystSnapshot> {
    log(`[hercules] analyst snapshot: ${repoKey} fallback (${reason})`);
    const dir = join(repoDir, EMPTY_NAME);
    await mkdir(dir, { recursive: true });
    if (!(await isReady(dir))) {
      await writeSandboxProfile(dir);
      await writeMarker(dir, 'empty');
    } else {
      await touchDir(dir);
    }
    return { dir, sha: null, grokHome };
  }

  async function prune(repoDir: string, currentSha: string): Promise<void> {
    let entries: string[];
    try {
      entries = await readdir(repoDir);
    } catch (err) {
      log(`[hercules] analyst snapshot: prune list failed: ${String(err)}`);
      return;
    }
    const candidates: { name: string; mtimeMs: number }[] = [];
    for (const name of entries) {
      if (name === EMPTY_NAME || name === currentSha || name.startsWith('.tmp-')) continue;
      const full = join(repoDir, name);
      try {
        const st = await stat(full);
        if (!st.isDirectory()) continue;
        candidates.push({ name, mtimeMs: st.mtimeMs });
      } catch {
        // skip
      }
    }
    candidates.sort((a, b) => b.mtimeMs - a.mtimeMs);
    const retain = Math.max(0, keep - 1);
    const toRemove = candidates.slice(retain);
    for (const c of toRemove) {
      try {
        await rm(join(repoDir, c.name), { recursive: true, force: true });
      } catch (err) {
        log(`[hercules] analyst snapshot: prune rm ${c.name}: ${String(err)}`);
      }
    }
  }

  async function buildSha(
    repo: RepoConfig,
    sha: string,
    repoDir: string,
    dir: string,
    grokHome: string | null,
  ): Promise<AnalystSnapshot> {
    const tmp = join(repoDir, `.tmp-${randomBytes(4).toString('hex')}`);
    try {
      await mkdir(tmp, { recursive: true });
      await opts.exportTree(repo, sha, tmp);
      await rm(join(tmp, '.grok'), { recursive: true, force: true });
      await writeSandboxProfile(tmp);
      await writeMarker(tmp, sha);
      try {
        await rename(tmp, dir);
      } catch (err) {
        if (isRenameRace(err)) {
          await rm(tmp, { recursive: true, force: true }).catch(() => {});
          if (await isReady(dir)) {
            await touchDir(dir);
            return { dir, sha, grokHome };
          }
          throw err;
        }
        throw err;
      }
      await prune(repoDir, sha);
      return { dir, sha, grokHome };
    } catch (err) {
      await rm(tmp, { recursive: true, force: true }).catch(() => {});
      throw err;
    }
  }

  return {
    grokHomePath,
    ensurePrivateHome,
    async ensure(repo: RepoConfig): Promise<AnalystSnapshot> {
      const grokHome = await ensurePrivateHome();
      const repoKey = repo.key;
      // Keys are validated upstream; an unexpected one must never become a path segment.
      if (!REPO_KEY_RE.test(repoKey)) {
        const quarantine = join(opts.root, '_invalid');
        await mkdir(quarantine, { recursive: true }).catch(() => {});
        return ensureEmpty(quarantine, 'invalid repo key', '<invalid>', grokHome);
      }
      const repoDir = join(opts.root, repoKey);

      let sha: string | null = null;
      try {
        sha = await opts.defaultBranchHead(repo);
      } catch {
        sha = null;
      }

      if (sha === null || !SHA_RE.test(sha)) {
        await mkdir(repoDir, { recursive: true });
        return ensureEmpty(
          repoDir,
          sha === null ? 'no default-branch tip' : 'malformed default-branch tip',
          repoKey,
          grokHome,
        );
      }

      const dir = join(repoDir, sha);
      if (await isReady(dir)) {
        await touchDir(dir);
        return { dir, sha, grokHome };
      }

      const flightKey = `${repoKey}\0${sha}`;
      const existing = inFlight.get(flightKey);
      if (existing) return existing;

      const promise = (async (): Promise<AnalystSnapshot> => {
        await mkdir(repoDir, { recursive: true });
        if (await isReady(dir)) {
          await touchDir(dir);
          return { dir, sha, grokHome };
        }
        try {
          return await buildSha(repo, sha, repoDir, dir, grokHome);
        } catch (err) {
          const reason = err instanceof Error ? err.message : String(err);
          return ensureEmpty(repoDir, reason, repoKey, grokHome);
        }
      })().finally(() => {
        inFlight.delete(flightKey);
      });

      inFlight.set(flightKey, promise);
      return promise;
    },
  };
}
